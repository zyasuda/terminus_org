/* 女性キャラの語尾の後始末(toFemaleVoice)の回帰テスト。
   実行: npm run test:voice
   例文は2026-08-07の実プレイのログ(logs/llm.jsonl)から採った、
   実際にリディア名義で出てしまった台詞。 */
import { toFemaleVoice } from "./voice.js";

let ng = 0;
const eq = (got, want, label) => {
  if (got !== want) { console.error(`NG ${label}\n   got:  ${got}\n   want: ${want}`); ng++; }
};

eq(toFemaleVoice("音がする方へ、慎重に進むべきだぜ。何か罠があるかもしれないからな。"),
   "音がする方へ、慎重に進むべきね。何か罠があるかもしれないからね。", "べきだぜ / からな");
eq(toFemaleVoice("待て。ただ壊すだけでは済まないかもしれないぞ。何か気配を感じる。"),
   "待って。ただ壊すだけでは済まないかもしれないわよ。何か気配を感じる。", "待て / かもしれないぞ");
eq(toFemaleVoice("ただの風じゃないな。何かが動いた痕跡だぜ。"),
   "ただの風じゃないわね。何かが動いた痕跡だわ。", "ないな / だぜ");
eq(toFemaleVoice("おお、すごいぞ！これで開けられるかもしれないな。"),
   "あら、すごいわよ！これで開けられるかもしれないわね。", "文頭のおお / ぞ！ / いな");
eq(toFemaleVoice("今は体力を温存すべきだぞ。本当に必要か？"),
   "今は体力を温存すべきよ。本当に必要か？", "べきだぞ");
eq(toFemaleVoice("やはり、この線路沿いは何かが動く場所だったようだな。"),
   "やはり、この線路沿いは何かが動く場所だったようね。", "ようだな");
eq(toFemaleVoice("注意して進むべきだろ？"), "注意して進むべきでしょう？", "だろ");

// 既に女性口調の文は触らない
for (const t of [
  "気をつけて、何か隠されているのかもしれないわね。",
  "わたしも賛成。あなたが受けるなら、同行するわ。",
  "遺工は、急いで触るものじゃないわ。"
]) eq(toFemaleVoice(t), t, `無変換: ${t}`);

console.log(ng ? `voice: NG ${ng}件` : "voice: OK");
process.exit(ng ? 1 : 0);
